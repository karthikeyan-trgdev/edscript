/** wa.me link for the site's WhatsApp number, with an opening message */
export function whatsappHref() {
  const { whatsapp, whatsappMessage } = content.footer.contact;
  const number = String(whatsapp || '').replace(/\D/g, '');
  return `https://wa.me/${number}${whatsappMessage ? `?text=${encodeURIComponent(whatsappMessage)}` : ''}`;
}
